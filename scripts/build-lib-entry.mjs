// Writes src/lib/index.ts: the one entry the published library exports.
//
// The catalog is the source of truth, so the entry is generated, not hand-kept: every component and pattern in
// contracts/index.json becomes `@/<ui|patterns>/<Name>/<Name>`, plus the few shared helpers screens import by hand.
// Names are re-exported one by one rather than with `export *`, so a name two modules both declare (ChartSeries,
// the same alias in BarChart and LineChart) is exported once instead of becoming ambiguous and vanishing.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.join(import.meta.dirname, "..");
const rel = (p) => path.join(root, p);
const index = JSON.parse(readFileSync(rel("contracts/index.json"), "utf8"));

/** Shared helpers that are not components but that screens import: the kit is not usable outside without them. */
const HELPERS = [
  "src/ui/inspect.ts",
  "src/ui/titleCase.ts",
  "src/patterns/AppShell/appNav.ts",
  "src/patterns/band.ts",
  "src/patterns/stick.ts",
];

/** The entry file for one catalog name. src/ui/Chart has no contract: it is the charts' internals, not a piece. */
function entryFor(name) {
  for (const base of ["src/ui", "src/patterns"]) {
    for (const ext of [".tsx", ".ts"]) {
      const p = `${base}/${name}/${name}${ext}`;
      if (existsSync(rel(p))) return p;
    }
  }
  throw new Error(`contracts/index.json lists ${name}, but there is no ${name}/${name}.tsx under src/ui or src/patterns`);
}

/** The names one module exports, split into values and types, read from the source the repo actually writes. */
function exportsOf(file) {
  const src = readFileSync(rel(file), "utf8");
  const values = [];
  const types = [];
  for (const m of src.matchAll(/^export\s+(?:async\s+)?(function|const|let|class|enum|type|interface)\s+([A-Za-z0-9_$]+)/gm)) {
    (m[1] === "type" || m[1] === "interface" ? types : values).push(m[2]);
  }
  for (const m of src.matchAll(/^export\s+(type\s+)?\{([^}]*)\}\s*(?:from\s*["'][^"']+["'])?\s*;?/gm)) {
    for (const part of m[2].split(",")) {
      const piece = part.trim();
      if (!piece) continue;
      const bare = piece.replace(/^type\s+/, "");
      const name = bare.split(/\s+as\s+/).pop().trim();
      if (!name || name === "default") continue;
      (m[1] || /^type\s/.test(piece) ? types : values).push(name);
    }
  }
  if (values.length === 0 && types.length === 0) throw new Error(`${file} exports nothing the entry can re-export`);
  return { values: [...new Set(values)], types: [...new Set(types)] };
}

const modules = [
  ...index.components.map((c) => entryFor(c.name)),
  ...index.patterns.map((p) => entryFor(p.name)),
  ...HELPERS,
];

const taken = new Map();
const lines = [];
const skipped = [];
for (const file of modules) {
  const { values, types } = exportsOf(file);
  const specifier = `../${file.replace(/^src\//, "").replace(/\.tsx?$/, "")}`;
  const keep = (names) => names.filter((n) => {
    const owner = taken.get(n);
    if (owner && owner !== file) {
      skipped.push(`${n} (${file}, already from ${owner})`);
      return false;
    }
    taken.set(n, file);
    return true;
  });
  const v = keep(values);
  const t = keep(types);
  if (v.length) lines.push(`export { ${v.join(", ")} } from "${specifier}";`);
  if (t.length) lines.push(`export type { ${t.join(", ")} } from "${specifier}";`);
}

// The tokens, in the order src/app/layout.tsx loads them: primitives, then the roles built on them, then the type
// and layout classes. They are imported here so the library build folds them and every component stylesheet into
// one dist/styles.css, ahead of the component rules that read them.
const TOKEN_CSS = ["primitives", "semantic", "typography", "layout"];

const header = [
  "// GENERATED by scripts/build-lib-entry.mjs from contracts/index.json. Do not edit by hand.",
  "//",
  "// The entry of the published library. Import the stylesheet once in the host app:",
  "//",
  "//   import \"agentic-bp-ds-kit/styles.css\";",
  "",
  ...TOKEN_CSS.map((n) => `import "../tokens/${n}.css";`),
  "",
].join("\n");

mkdirSync(rel("src/lib"), { recursive: true });
writeFileSync(rel("src/lib/index.ts"), `${header}${lines.join("\n")}\n`);
// The skips are the shared chart types (ChartFormat, ChartIntent, ChartSeries) that every chart re-exports: the
// first chart wins and the name stays unambiguous. Pass --verbose to see each one.
const verbose = process.argv.includes("--verbose");
console.log(`entry: ${modules.length} modules, ${taken.size} names, ${skipped.length} duplicate names skipped`);
if (verbose) for (const s of skipped) console.log(`  skipped ${s}`);
