/**
 * Widget sizes: how wide and how tall a tile is, derived from the layout tokens rather than typed in.
 *
 * A tile is `<columns>x<rows>`. Columns are the kit's 12-column split grid (`.layout-split`, --grid-columns)
 * with the lg gutter between them, measured in the reference frame: the AppShell at --grid-width-xl (1440),
 * the side nav open (--side-nav-rail-open) and the page inset of `.layout-content` (--layout-margin-md) on
 * both sides. Rows are a fixed step on the 4px grid with the same gutter between them.
 *
 *   readLayoutTokens(root)  — the few token values the sizes are made from
 *   deriveSizes(tokens)     — the contents of contracts/widget-sizes.json
 *   writeSizes(root)        — writes contracts/widget-sizes.json, returns { file, changed, sizes }
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { repoRoot } from "../review/catalog.mjs";

/** Every tile size there is. A template allows some of them. */
export const SIZE_IDS = ["3x1", "4x1", "6x1", "12x1", "4x2", "6x2", "12x2", "6x3", "12x3"];

/** Where the derived table lives. */
export const SIZES_FILE = "contracts/widget-sizes.json";

/**
 * One row of a tile, in 4px steps. layout.css has no row track, so this is the kit's own choice: 42 steps
 * (168px) holds a section header over a Scoreboard, and two rows plus a gutter (360px) hold a section header,
 * a 240px chart and its legend.
 */
export const ROW_STEPS = 42;

/** The first definition of a custom property in a CSS text (the default density, ahead of the overrides). */
function firstValue(css, name) {
  const match = new RegExp(`${name.replace(/[-]/g, "\\-")}\\s*:\\s*([^;]+);`).exec(css);
  return match ? match[1].trim() : null;
}

/** A token's value in px, following var() references inside the same text. */
function px(css, name, seen = new Set()) {
  if (seen.has(name)) throw new Error(`${name} refers to itself.`);
  seen.add(name);
  const value = firstValue(css, name);
  if (value === null) throw new Error(`No token ${name} in the token files.`);
  const ref = /^var\((--[a-z0-9-]+)\)$/.exec(value);
  if (ref) return px(css, ref[1], seen);
  const n = /^(\d+(?:\.\d+)?)(px)?$/.exec(value);
  if (!n) throw new Error(`${name} is ${value}, not a px value.`);
  return Number(n[1]);
}

/** The token values the sizes are made from. */
export function readLayoutTokens(root = repoRoot) {
  const css = ["src/tokens/primitives.css", "src/tokens/semantic.css"]
    .map((file) => join(root, file))
    .filter((file) => existsSync(file))
    .map((file) => readFileSync(file, "utf8"))
    .join("\n");
  return {
    columns: px(css, "--grid-columns"),
    gutter: px(css, "--layout-gutter-lg"),
    margin: px(css, "--layout-margin-md"),
    frame: px(css, "--grid-width-xl"),
    nav: px(css, "--side-nav-rail-open"),
    step: px(css, "--ref-space-200"),
  };
}

const round = (n) => Math.round(n * 100) / 100;

/** The size table. Widths are fractional px, as the grid draws them; heights are whole. */
export function deriveSizes(tokens) {
  const { columns, gutter, margin, frame, nav, step } = tokens;
  const content = frame - nav - 2 * margin;
  const column = (content - (columns - 1) * gutter) / columns;
  const row = ROW_STEPS * step;
  const sizes = {};
  for (const id of SIZE_IDS) {
    const [cols, rows] = id.split("x").map(Number);
    sizes[id] = {
      columns: cols,
      rows,
      width: round(cols * column + (cols - 1) * gutter),
      height: rows * row + (rows - 1) * gutter,
    };
  }
  return {
    $comment:
      "Generated by npm run widget -- sizes from src/tokens/primitives.css. Do not edit by hand: change the tokens and run it again.",
    frame: {
      width: frame,
      nav,
      margin,
      content,
      columns,
      gutter,
      column: round(column),
      row,
      note: "The reference frame: AppShell at --grid-width-xl with the nav open (--side-nav-rail-open) and the .layout-content inset (--layout-margin-md). Columns are the .layout-split grid (--grid-columns, --layout-gutter-lg). A row is 42 steps of the 4px grid (--ref-space-200), with the same gutter between rows.",
    },
    sizes,
  };
}

/** Write contracts/widget-sizes.json from the tokens. */
export function writeSizes(root = repoRoot) {
  const file = join(root, SIZES_FILE);
  const next = `${JSON.stringify(deriveSizes(readLayoutTokens(root)), null, 2)}\n`;
  const before = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (before !== next) writeFileSync(file, next);
  return { file: SIZES_FILE, changed: before !== next, sizes: JSON.parse(next).sizes };
}

/** The size table as it is on disk (what templates and the renderer read). */
export function loadSizes(root = repoRoot) {
  const file = join(root, SIZES_FILE);
  if (!existsSync(file)) return deriveSizes(readLayoutTokens(root));
  return JSON.parse(readFileSync(file, "utf8"));
}
